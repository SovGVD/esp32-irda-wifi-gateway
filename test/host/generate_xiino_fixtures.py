#!/usr/bin/env python3
"""Regenerate independent OpenXiino HTML/mode9/image fixtures (Pillow, requests).

Only colour conversion is exercised; bitstring belongs to unused upstream
grayscale routines, so it is not required to regenerate these fixtures.
"""
import io
import os
from pathlib import Path
import random
import sys
import types

ROOT = Path(__file__).resolve().parents[2]
UPSTREAM = ROOT / "third_party/openxiino"
sys.path.insert(0, str(UPSTREAM))
os.chdir(UPSTREAM)
try:
    import bitstring
except ImportError:
    sys.modules["bitstring"] = types.ModuleType("bitstring")
from PIL import Image
from lib.xiino_html_converter import XiinoHTMLParser
from lib.xiino_image_converter import EBDConverter
from lib.mode9 import compress_mode9
from lib.xiino_palette_common import PALETTE


def literal(value):
    if isinstance(value, str):
        value = value.encode("utf-8")
    return '"' + "".join(f"\\{b:03o}" for b in value) + '"'


html_cases = [
    "<html><head><title>Title</title></head><body><h1>Hello</h1><p>World</p></body></html>",
    '<body><a href="../next?q=1&amp;x=2#top" title="A &quot;B&quot;">Next</a></body>',
    "<body><p>Before <span>inside</span> after</p><p>Visible</p></body>",
    "<body><!-- hidden --><script>if (x < 4) { alert('hi'); }</script>hidden<p>Shown</p></body>",
    '<body><p>Caf&eacute; &copy; &#233; &mdash; &#x1f600; &notit; &NotEqualTilde;</p></body>',
    '<body><input disabled type="text" value="X"><br/><hr /><p>Fin</p></body>',
    '<style>body { color: red; }</style><body> Body <div> Text </div></body>',
    '<form action="/post" method="GET"><input name="q"><select name="s"><option value="1">One</option></select></form>',
]
out = ["// Generated by test/host/generate_xiino_fixtures.py from OpenXiino e9ef506.\n",
       "struct HtmlFixture { const char *input, *output; };\nstatic const HtmlFixture html_fixtures[] = {\n"]
for text in html_cases:
    parser = XiinoHTMLParser(base_url="https://example.test/dir/page")
    parser.feed(text)
    converted = parser.get_parsed_data().encode("latin-1", errors="ignore")
    out.append("{" + literal(text) + "," + literal(converted) + "},\n")
out.append("};\nstruct ModeFixture { unsigned width,height; const char *pixels; const char *encoded; size_t encoded_size; };\nstatic const ModeFixture mode_fixtures[] = {\n")
random.seed(4040)
for width in (1, 2, 3, 5, 8, 16, 153):
    for kind in ("solid", "random", "copy", "offset"):
        height = 3
        pixels = []
        first = [random.randrange(len(PALETTE)) for _ in range(width)]
        for y in range(height):
            if kind == "solid":
                row = [0] * width
            elif kind == "random":
                row = [random.randrange(len(PALETTE)) for _ in range(width)]
            elif kind == "copy":
                row = first
            else:
                row = first[y:] + first[:y]
                row = (row + first)[:width]
            pixels.extend(row)
        image = Image.new("RGB", (width, height))
        image.putdata([PALETTE[p] for p in pixels])
        # Quantizing an RGB image can change palette aliases. Recover the exact
        # indices consumed by upstream after Pillow's quantize/convert step.
        palette = Image.open("lib/paletised.png")
        quantized = image.quantize(palette=palette).convert("RGB")
        indices = bytes(PALETTE.index(p) if p in PALETTE else 0xE6 for p in quantized.getdata())
        encoded = compress_mode9(image)
        out.append(f"{{{width},{height}," + literal(indices) + "," + literal(encoded) + f",{len(encoded)}}},\n")
out.append("};\nstruct ImageFixture { const char *bytes; size_t size; const char *img,*ebd; };\nstatic const ImageFixture image_fixtures[] = {\n")
for fmt, size, colour in [("PNG",(8,6),(255,255,255)), ("JPEG",(12,8),(255,0,0)),
                           ("GIF",(10,8),(0,0,0)), ("BMP",(7,5),(0,255,0)),
                           ("PNG",(400,2),(255,255,255))]:
    image = Image.new("RGB", size, colour)
    file = io.BytesIO()
    image.save(file, format=fmt)
    decoded = Image.open(io.BytesIO(file.getvalue()))
    ebd = EBDConverter(decoded).convert_colour(compressed=True)
    out.append("{" + literal(file.getvalue()) + f",{len(file.getvalue())}," + literal(ebd.generate_img_tag("#1")) + "," + literal(ebd.generate_ebdimage_tag(1)) + "},\n")
out.append("};\n")
(ROOT / "test/host/data/xiino_fixtures.h").write_text("".join(out))
print("Generated upstream HTML, mode9 and image fixtures")
